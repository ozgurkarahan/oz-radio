# Per-principal daily generation quota
# ---------------------------------------------------------------------------
class DailyQuota:
    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._counts: dict[tuple[str, str], int] = {}

    @staticmethod
    def limit() -> int:
        return _env_int("DAILY_GENERATION_QUOTA", 50)

    def consume(self, principal_id: str, amount: int = 1) -> None:
        day = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        key = (principal_id, day)
        with self._lock:
            # Drop counters from previous days.
            for k in [k for k in self._counts if k[1] != day]:
                del self._counts[k]
            used = self._counts.get(key, 0)
            if used + amount > self.limit():
                raise HTTPException(
                    status_code=429,
                    detail="Daily generation quota exceeded. Try again tomorrow (UTC).",
                )
            self._counts[key] = used + amount

    def reset(self) -> None:
        with self._lock:
            self._counts.clear()


DAILY_QUOTA = DailyQuota()


def consume_quota(principal: Principal = Depends(require_admin)) -> Principal:
    """Dependency: admin + one unit of the caller's daily generation quota."""
    DAILY_QUOTA.consume(principal.user_id)
    return principal


# ---------------------------------------------------------------------------
# Global concurrency caps
# ---------------------------------------------------------------------------
class ConcurrencyLimiter:
    def __init__(self, env_name: str, default: int) -> None:
        self._env_name = env_name
        self._default = default
        self._lock = threading.Lock()
        self._active = 0

    def limit(self) -> int:
        return _env_int(self._env_name, self._default, minimum=1)

    @property
    def active(self) -> int:
        return self._active

    def try_acquire(self) -> bool:
        with self._lock:
            if self._active >= self.limit():
                return False
            self._active += 1
            return True

    def release(self) -> None:
        with self._lock:
            self._active = max(0, self._active - 1)

    def reset(self) -> None:
        with self._lock:
            self._active = 0


class BlockingLimiter:
    """Counting semaphore whose callers *wait* for a free slot instead of failing.

    For CPU-heavy steps that must queue (the podcast video compose). The size
    is re-read from ``env_name`` while waiting, so raising it frees waiters.
    Blocks the calling thread: use it from worker threads, never on the
    event loop.
    """

    _POLL_SEC = 1.0

    def __init__(self, env_name: str, default: int) -> None:
        self._env_name = env_name
        self._default = default
        self._cond = threading.Condition()
        self._active = 0

    def limit(self) -> int:
        return _env_int(self._env_name, self._default, minimum=1)

    @property
    def active(self) -> int:
        return self._active

    def acquire(self, timeout: Optional[float] = None) -> bool:
        """Take a slot, waiting up to ``timeout`` seconds (None = forever); False on timeout."""
        end = None if timeout is None else time.monotonic() + max(0.0, timeout)
        with self._cond:
            while self._active >= self.limit():
                remaining = None if end is None else end - time.monotonic()
                if remaining is not None and remaining <= 0:
                    return False
                self._cond.wait(self._POLL_SEC if remaining is None else min(remaining, self._POLL_SEC))
            self._active += 1
            return True

    def release(self) -> None:
        with self._cond:
            self._active = max(0, self._active - 1)
            self._cond.notify_all()

    @contextmanager
    def slot(self, timeout: Optional[float] = None) -> Iterator[None]:
        """``with limiter.slot():`` — ``TimeoutError`` when no slot frees up in time."""
        if not self.acquire(timeout):
            raise TimeoutError(f"no free {self._env_name} slot")
        try:
            yield
        finally:
            self.release()

    def reset(self) -> None:
        with self._cond:
            self._active = 0
            self._cond.notify_all()


