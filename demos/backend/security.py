def is_valid(value: Optional[str], pattern: re.Pattern[str]) -> bool:
    return isinstance(value, str) and pattern.fullmatch(value) is not None


def require_id(value: Optional[str], pattern: re.Pattern[str], what: str = "Item") -> str:
    """Return ``value`` when it matches ``pattern``; otherwise raise 404."""
    if not is_valid(value, pattern):
        raise HTTPException(status_code=404, detail=f"{what} not found")
    return value  # type: ignore[return-value]


# ---------------------------------------------------------------------------
# Safe filesystem joins
# ---------------------------------------------------------------------------
def _unsafe_segment(part: str) -> bool:
    if not part or part in {".", ".."}:
        return True
    if "\x00" in part or "\\" in part or "%" in part or ":" in part:
        return True
    return False


def safe_join(base: Path | str, *parts: str) -> Optional[Path]:
    """Join untrusted relative ``parts`` under ``base``.

    Returns ``None`` for absolute paths, drive letters, backslashes, percent
    sequences (double-encoding), NUL bytes, ``.``/``..`` segments, or any
    result that resolves outside ``base`` (symlinks included).
    """
    base_path = Path(base).resolve()
    segments: list[str] = []
    for raw in parts:
        if not isinstance(raw, str) or not raw:
            return None
        if raw.startswith("/") or "\\" in raw:
            return None
        for seg in PurePosixPath(raw).parts:
            if _unsafe_segment(seg):
                return None
            segments.append(seg)
        # PurePosixPath collapses "a//b" and drops trailing "/", so also
        # reject literal dot segments in the raw string.
        if any(s in {".", ".."} for s in raw.split("/")):
            return None
    if not segments:
        return None
    candidate = base_path.joinpath(*segments)
    try:
        resolved = candidate.resolve()
    except (OSError, RuntimeError):
        return None
    if not resolved.is_relative_to(base_path):
        return None
    return resolved


_FILENAME_BAD = re.compile(r"[^A-Za-z0-9 ._()\-]+")


def safe_filename(name: Optional[str], default: str = "upload", max_len: int = 120) -> str:
    """Reduce a client-supplied file name to a safe base name.

    Strips any directory part (``/`` or ``\\``), control/special characters
    and leading dots, so it can be used in blob names and display titles.
    """
    base = (name or "").replace("\\", "/").rsplit("/", 1)[-1]
    base = _FILENAME_BAD.sub("_", base).strip(" ._") or default
    if len(base) > max_len:
        stem, dot, ext = base.rpartition(".")
        base = (stem[: max_len - len(ext) - 1] + "." + ext) if dot and len(ext) <= 10 else base[:max_len]
    return base


# ---------------------------------------------------------------------------
# Upload size limits
# ---------------------------------------------------------------------------
MAX_UPLOAD_BYTES = 50 * 1024 * 1024


async def read_upload_limited(file: UploadFile, max_bytes: int = MAX_UPLOAD_BYTES) -> bytes:
    """Read an upload in chunks, failing with 413 above ``max_bytes``."""
    chunks: list[bytes] = []
    total = 0
    while True:
        chunk = await file.read(1 << 20)
        if not chunk:
            break
        total += len(chunk)
        if total > max_bytes:
            raise HTTPException(
                status_code=413,
                detail=f"File too large (max {max_bytes // (1024 * 1024)} MB)",
            )
        chunks.append(chunk)
    return b"".join(chunks)


