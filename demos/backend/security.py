def _parse_ip(value: str) -> Optional[str]:
    value = (value or "").strip().strip('"')
    if not value:
        return None
    candidates = [value]
    if value.startswith("[") and "]" in value:          # [v6]:port
        candidates.append(value[1:value.index("]")])
    elif value.count(":") == 1:                          # v4:port
        candidates.append(value.split(":", 1)[0])
    for c in candidates:
        try:
            return str(ipaddress.ip_address(c))
        except ValueError:
            continue
    return None


def client_ip(headers: Mapping[str, str], peer: Optional[str] = None) -> str:
    """Best-effort client IP for per-IP demo quotas.

    Trust assumption: the app is only reachable through the Azure Container
    Apps ingress (envoy). ACA *appends* the real peer address to any
    client-supplied ``X-Forwarded-For`` and documents that "only the rightmost
    IP is provided by Azure Container Apps", so the rightmost entry is the one
    we trust (left-hand entries are attacker-controlled). Without the header
    (local dev / tests) the socket peer is used.
    """
    xff = headers.get("x-forwarded-for") or ""
    if xff:
        ip = _parse_ip(xff.split(",")[-1])
        if ip:
            return ip
    return _parse_ip(peer or "") or (peer or "unknown")


