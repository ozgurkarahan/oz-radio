# CORS / WebSocket Origin
# ---------------------------------------------------------------------------
def allowed_origins() -> list[str]:
    raw = os.environ.get("ALLOWED_ORIGINS") or ""
    return [o.strip().rstrip("/") for o in raw.split(",") if o.strip()]


_LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1"}


def origin_allowed(headers: Mapping[str, str]) -> bool:
    """Validate the WebSocket ``Origin`` header.

    - Same-origin is always allowed: Origin host[:port] must equal the Host header.
    - ``ALLOWED_ORIGINS`` adds extra exact-match origins (e.g. a Teams host).
    - ``AUTH_MODE=disabled`` additionally accepts localhost origins (Vite
      dev proxy) and a missing Origin (non-browser local tooling).
    """
    origin = (headers.get("origin") or "").strip().rstrip("/")
    dev = auth_mode() == "disabled"
    if not origin:
        return dev
    if origin in allowed_origins():
        return True
    try:
        parts = urlsplit(origin)
    except ValueError:
        return False
    host = (headers.get("host") or "").strip().lower()
    if parts.scheme in {"http", "https"} and parts.netloc.lower() == host and host:
        return True
    if dev:
        try:
            hostname = (urlsplit(origin).hostname or "").lower()
        except ValueError:
            return False
        return hostname in _LOCAL_HOSTS
    return False
